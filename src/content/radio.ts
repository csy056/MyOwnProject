export function unlockedRadio(totals: RunTotals): RadioLog[] {
  return RADIO_LOGS.filter((r) => totals[r.condition.kind] >= r.condition.atLeast);
}

export function newlyUnlocked(before: RunTotals, after: RunTotals): RadioLog[] {
  const had = new Set(unlockedRadio(before).map((r) => r.id));
  return unlockedRadio(after).filter((r) => !had.has(r.id));
}
